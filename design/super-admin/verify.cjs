const { chromium } = require("@playwright/test")
const fs = require("node:fs")
const path = require("node:path")
;(async () => {
  const browser = await chromium.launch({ channel: "msedge", headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 })
  const errors = []
  page.on("pageerror", error => errors.push(error.message))
  const output = path.join(__dirname, "screenshots")
  fs.mkdirSync(output, { recursive: true })
  for (const [width, label] of [[1440, "desktop"], [390, "mobile"]]) {
    await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 })
    for (const route of ["directory", "overview", "onboarding"]) {
      await page.goto("http://127.0.0.1:5180/#" + route)
      await page.locator("main h1").waitFor()
      await page.evaluate(() => document.fonts.ready)
      await page.waitForTimeout(250)
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
      if (overflow) throw new Error("Horizontal overflow: " + label + " " + route)
      await page.screenshot({ path: path.join(output, label + "-" + route + ".png"), fullPage: true })
    }
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto("http://127.0.0.1:5180/#directory")
  await page.getByLabel("Search merchants").fill("Anushq")
  if (await page.locator("#merchant-rows .merchant-link").count() !== 1) throw new Error("Search failed")
  await page.getByLabel("Search merchants").fill("")
  await page.getByRole("button", { name: "Needs attention", exact: true }).click()
  await page.getByText("No merchants match").waitFor()
  await page.goto("http://127.0.0.1:5180/#onboarding")
  await page.getByLabel("Merchant name").fill("")
  await page.getByRole("button", { name: "Continue", exact: true }).click()
  if (await page.locator("#f-name").getAttribute("aria-invalid") !== "true") throw new Error("Validation missing")
  await page.getByLabel("Merchant name").fill("Sagar Sportz")
  await page.getByRole("button", { name: "Continue", exact: true }).click()
  await page.getByRole("button", { name: "Connect existing", exact: true }).click()
  await page.getByLabel("Medusa backend URL").waitFor()
  await page.getByRole("button", { name: "Continue", exact: true }).click()
  await page.getByRole("button", { name: "Hosting provider", exact: true }).click()
  await page.getByRole("option", { name: "Netlify", exact: true }).click()
  if (!(await page.getByRole("button", { name: "Hosting provider", exact: true }).innerText()).includes("Netlify")) throw new Error("Dropdown failed")
  await page.locator('[data-step="6"]').click()
  await page.getByRole('switch', { name: 'Product reviews', exact: true }).click()
  await page.locator('[data-step="7"]').click()
  await page.getByText('Product reviews', { exact: true }).waitFor()
  await page.locator('[data-step="6"]').click()
  if(await page.getByRole('switch', { name: 'Product reviews', exact: true }).getAttribute('aria-checked')!=='true')throw Error('Feature choice lost')
  await page.setViewportSize({width:390,height:844})
  await page.waitForTimeout(350)
  await page.screenshot({path:path.join(output,'mobile-features.png'),fullPage:true})
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Features overflow')
  await page.setViewportSize({width:1440,height:1000})
  await page.goto('http://127.0.0.1:5180/#editor')
  await page.getByRole('heading',{name:'Merchants',exact:true}).waitFor()
  if(await page.locator('[data-nav="editor"]').count())throw Error('Merchant editor still in platform navigation')
  await page.goto('http://127.0.0.1:5180/#overview')
  await page.getByRole('button',{name:'Fullscreen preview',exact:true}).click()
  const originAnimation=await page.locator('#preview-dialog').evaluate(el=>el.getAnimations().some(a=>a.effect.getKeyframes().some(k=>String(k.transform).includes('translate('))))
  if(!originAnimation)throw Error('Origin animation absent')
  await page.waitForTimeout(350)
  await page.keyboard.press('Escape')
  await page.locator('#preview-dialog').waitFor({state:'hidden'})
  if(!await page.getByRole('button',{name:'Fullscreen preview',exact:true}).evaluate(el=>el===document.activeElement))throw Error('Focus not restored')
  await page.getByRole("button", { name: "Preview loading" }).click()
  if (await page.locator("main").getAttribute("aria-busy") !== "true") throw new Error("Loading state absent")
  await page.waitForTimeout(1250)
  await page.getByRole("heading", { name: "Storefront preview", exact: true }).waitFor()
  await page.emulateMedia({ reducedMotion: "reduce" })
  const animation = await page.locator("main").evaluate(el => getComputedStyle(el).animationName)
  if (animation !== "none") throw new Error("Reduced motion not respected")
  if (errors.length) throw new Error(errors.join("\n"))
  console.log("PASS: 6 responsive screens, merchant-only editor excluded, features, preview modal, search/filter, wizard validation, dropdown, skeletons, reduced motion; no JS errors")
  await browser.close()
})().catch(e => { console.error(e); process.exitCode = 1 })
